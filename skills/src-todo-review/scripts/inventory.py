"""List the XXX/TODO/FIXME/HACK/KLUDGE markers in the comments of a FreeBSD
src tree, one JSON object per comment block.

    inventory.py [-C srcdir] [-c paths.conf] > inventory.jsonl

Only files tracked by git at HEAD are read, through "git grep", so the
working tree must match HEAD.  Markers outside comments (identifiers,
string literals such as mkstemp templates) are counted in the summary on
stderr but not listed.  Manual page text is listed with "doctext": true,
since a marker there is visible to readers.

Each item has a stable "id": a hash of the path and the comment text, so
the same comment keeps its id when lines move.  An edited comment gets a
new id and is triaged again.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict

MARKERS = ("XXX", "XXXX", "TODO", "FIXME", "HACK", "KLUDGE")
# Not part of a longer word: XXXXXX (mkstemp) and FIXME_FOO do not match.
MARKER_RE = re.compile(r"(?<![A-Za-z0-9_])(XXXX?|TODO|FIXME|HACK|KLUDGE)(?![A-Za-z0-9_])")
GREP_ERE = r"(^|[^A-Za-z0-9_])(XXXX?|TODO|FIXME|HACK|KLUDGE)([^A-Za-z0-9_]|$)"

C_EXT = {".c", ".h", ".cc", ".cpp", ".cxx", ".hh", ".hpp", ".m", ".y",
         ".l", ".d", ".dts", ".dtsi", ".dtso", ".rs", ".inc", ".def", ".x",
         ".ldscript", ".lds", ".ld", ".hx", ".java", ".js", ".go"}
ASM_EXT = {".S", ".s", ".asm"}
HASH_EXT = {".sh", ".mk", ".py", ".pl", ".pm", ".awk", ".sed", ".conf",
            ".cfg", ".tcl", ".exp", ".ksh", ".kshlib", ".csh", ".rb",
            ".subr", ".ucl", ".yml", ".yaml", ".toml", ".options", ".bash",
            ".zsh", ".t", ".test", ".cmake", ".fdb", ".cnf", ".src"}
ROFF_EXT = {".1", ".2", ".3", ".4", ".5", ".6", ".7", ".8", ".9", ".mdoc",
            ".man", ".ms", ".me", ".roff", ".tmac", ".mm"}
SGML_EXT = {".xml", ".html", ".htm", ".sgml", ".xsl", ".dtd", ".svg"}
LUA_EXT = {".lua"}
FORTH_EXT = {".4th"}
M4_EXT = {".m4"}
SEMI_EXT = {".master"}
# Never code: data, test outputs, plain prose.
SKIP_EXT = {".txt", ".md", ".json", ".out", ".ok", ".err", ".stdout",
            ".stderr", ".depend", ".uu", ".hex", ".pem", ".kbd", ".fnt",
            ".map", ".csv", ".po", ".diff", ".patch", ".0", ".Z", ".gz"}
HASH_NAMES = {"Makefile", "GNUmakefile", "Kyuafile", "NOTES", "files",
              "options", "DEFAULTS", "MINIMAL", "GENERIC", "LINT"}
# Kernel and release configurations, rc.d scripts and the like.
HASH_DIRS = ("/conf/", "/rc.d/", "libexec/rc/", "etc/", "release/")

C_TOKEN_RE = re.compile(
    r"//[^\n]*|/\*[\s\S]*?\*/|\"(?:\\[\s\S]|[^\"\\\n])*\"|'(?:\\[\s\S]|[^'\\\n])*'")
LUA_TOKEN_RE = re.compile(
    r"--\[(=*)\[[\s\S]*?\]\1\]|--[^\n]*|\"(?:\\.|[^\"\\\n])*\"|"
    r"'(?:\\.|[^'\\\n])*'|\[(=*)\[[\s\S]*?\]\2\]")
SGML_TOKEN_RE = re.compile(r"<!--[\s\S]*?-->")
CPP_DIRECTIVE_RE = re.compile(
    r"^\s*#\s*(define|include|if|ifdef|ifndef|else|elif|endif|undef|error|"
    r"warning|pragma|line)\b")
FUNC_DEF_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*\(")
NOT_FUNCTIONS = {"if", "for", "while", "switch", "return", "sizeof", "do",
                 "else", "int", "void", "char", "long", "short", "unsigned",
                 "signed", "static", "struct", "union", "enum", "const",
                 "extern", "typedef", "bool", "inline", "volatile"}
# Not "(generated from NOTES)": sys/conf/options names another file.
GENERATED_RE = re.compile(
    r"DO NOT EDIT|automatically generated|generated automatically|"
    r"auto-generated|autogenerated|(?<!\()generated (?:by|from)", re.I)
DECOR_RE = re.compile(r"^\s*(?:/\*+|\*+/|\*+|//+|#+|--+|;+|\.?\\\"|dnl\b|\\|@|!)?\s?")


def load_paths_conf(path):
    classes = defaultdict(list)
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if len(line) == 2:
                classes[line[0]].append(line[1])
    return classes


def prefixed(path, prefixes):
    return any(path.startswith(p) for p in prefixes)


def lang_of(path, first_line):
    base = os.path.basename(path)
    root, ext = os.path.splitext(base)
    if base.startswith("Makefile"):
        return "hash"
    if ext in SKIP_EXT:
        return None
    if ext in C_EXT:
        return "c"
    if ext in ASM_EXT:
        return "asm"
    if ext in ROFF_EXT:
        return "roff"
    if ext in HASH_EXT or base.startswith("Makefile") or base in HASH_NAMES:
        return "hash"
    if ext in SGML_EXT:
        return "sgml"
    if ext in LUA_EXT:
        return "lua"
    if ext in FORTH_EXT:
        return "forth"
    if ext in M4_EXT:
        return "m4"
    if ext in SEMI_EXT:
        return "semi"
    if first_line.startswith("#!"):
        return "lua" if "lua" in first_line else "hash"
    if base.startswith(("files.", "options.", "std.")) or \
            any(d in "/" + path for d in HASH_DIRS):
        return "hash"
    return "unknown"


class Comments:
    """Comment spans of one file, as (start, end, kind) character offsets."""

    def __init__(self, text, lang):
        self.text = text
        self.lang = lang
        self.spans = []
        if lang in ("c", "asm", "semi", "unknown"):
            for m in C_TOKEN_RE.finditer(text):
                if m.group(0)[0] == "/":
                    kind = "block" if m.group(0)[1] == "*" else "line"
                    self.spans.append((m.start(), m.end(), kind))
        elif lang == "lua":
            for m in LUA_TOKEN_RE.finditer(text):
                s = m.group(0)
                if s.startswith("--"):
                    self.spans.append((m.start(), m.end(),
                                       "block" if s.startswith("--[") else "line"))
        elif lang == "sgml":
            for m in SGML_TOKEN_RE.finditer(text):
                self.spans.append((m.start(), m.end(), "block"))
        self.starts = [s[0] for s in self.spans]

    def span_at(self, off):
        lo, hi = 0, len(self.spans)
        while lo < hi:
            mid = (lo + hi) // 2
            if self.spans[mid][0] <= off:
                lo = mid + 1
            else:
                hi = mid
        if lo and self.spans[lo - 1][0] <= off < self.spans[lo - 1][1]:
            return self.spans[lo - 1]
        return None


def hash_comment_col(line, lang):
    """Column where a line comment starts, or -1.  Quotes are tracked so
    that '#' inside a string does not count; a '#' must follow whitespace or
    start the line, as in sh(1) ("$#" and "${#x}" are not comments)."""
    if lang == "m4":
        m = re.search(r"(?<![A-Za-z0-9_])dnl\b", line)
        if m:
            return m.start()
    if lang == "semi":
        q = None
        for i, ch in enumerate(line):
            if q:
                q = None if ch == q else q
            elif ch in "\"'":
                q = ch
            elif ch == ";":
                return i
        return -1
    if lang == "forth":
        m = re.search(r"(^|\s)\\(\s|$)", line)
        if m:
            return m.start() + len(m.group(1))
        m = re.search(r"(^|\s)\(\s", line)
        return m.start() + len(m.group(1)) if m else -1
    q = None
    prev = " "
    for i, ch in enumerate(line):
        if q:
            if ch == "\\" and q == '"':
                prev = ch
                continue
            if ch == q and prev != "\\":
                q = None
        elif ch in "\"'" and prev != "\\":
            q = ch
        elif ch == "#" and (prev.isspace() or prev in ";(" or i == 0):
            return i
        prev = ch
    return -1


def roff_comment_col(line):
    i = line.find('\\"')
    return i if i >= 0 else -1


def asm_comment_col(line, upto):
    """In assembly a marker is never an operand, so any comment character
    before it on the line starts the comment."""
    if CPP_DIRECTIVE_RE.match(line):
        return -1
    best = -1
    for tok in ("#", ";", "@", "!", "//", "|"):
        i = line.find(tok, 0, upto)
        if i >= 0 and (best < 0 or i < best):
            best = i
    return best


def clean_comment(lines):
    out = []
    for ln in lines:
        ln = ln.rstrip()
        ln = re.sub(r"\*+/\s*$", "", ln)
        ln = DECOR_RE.sub("", ln, count=1)
        out.append(ln.rstrip())
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def normalize(text):
    return " ".join(text.split())


def enclosing_function(lines, idx):
    """style(9) puts a function name at the start of a line; walk back to it
    unless a closing brace at column 0 says we left a function first."""
    for i in range(idx, max(-1, idx - 3000), -1):
        ln = lines[i]
        if ln.startswith("}"):
            return ""
        m = FUNC_DEF_RE.match(ln)
        if m and m.group(1) not in NOT_FUNCTIONS and is_func_header(lines, i):
            return m.group(1)
    return ""


def is_func_header(lines, i):
    """The parameter list closes within a few lines and the body's brace
    follows, possibly after K&R parameter declarations."""
    for j in range(i, min(len(lines), i + 8)):
        s = lines[j].rstrip()
        if s.endswith(";") or s.endswith("\\"):
            return False
        if s.endswith(")") or s.endswith(") {"):
            if s.endswith("{"):
                return True
            for k in range(j + 1, min(len(lines), j + 12)):
                t = lines[k].rstrip()
                if t.startswith("{"):
                    return True
                if not t.endswith(";") or not t[:1].isspace():
                    return False
            return False
    return False


def area_of(path):
    parts = path.split("/")[:-1]
    if not parts:
        return "(top)"
    depth = 2
    if parts[0] == "sys" and len(parts) > 1 and parts[1] in (
            "dev", "compat", "fs", "netpfil", "geom", "cam", "arm", "arm64",
            "powerpc", "riscv", "modules", "security", "netgraph", "ofed",
            "gnu", "x86", "amd64", "i386", "crypto", "dts", "xen"):
        depth = 3
    elif "/".join(parts[:2]) in ("lib/libc", "tests/sys", "tools/tools",
                                 "tools/regression", "share/man", "tools/test",
                                 "usr.sbin/bsnmpd", "lib/msun", "stand/efi"):
        depth = 3
    return "/".join(parts[:depth])


def line_comment_block(lines, idx, col_of, lang):
    """Extend a line comment on line idx over the comment-only lines above
    and below it.  A trailing comment after code stands alone."""
    col = col_of(lines[idx])
    if col < 0:
        return None
    first = last = idx
    if lines[idx][:col].strip() == "":
        def comment_only(i):
            c = col_of(lines[i])
            return c >= 0 and lines[i][:c].strip() == ""
        while first > 0 and comment_only(first - 1):
            first -= 1
        while last + 1 < len(lines) and comment_only(last + 1):
            last += 1
    body = []
    for i in range(first, last + 1):
        c = col_of(lines[i])
        body.append(lines[i][c:])
    return first, last, body


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-C", dest="src", default=".", help="src tree (git checkout)")
    ap.add_argument("-c", dest="conf",
                    default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                         "paths.conf"))
    ap.add_argument("-m", dest="misses", metavar="file",
                    help="also write the hits outside comments to this file")
    ap.add_argument("paths", nargs="*", help="limit to these pathspecs")
    args = ap.parse_args()
    misses = open(args.misses, "w") if args.misses else None

    classes = load_paths_conf(args.conf)
    pathspec = list(args.paths) or ["."]
    pathspec += [":(exclude)" + p for p in classes["exclude"]]
    head = subprocess.run(["git", "-C", args.src, "rev-parse", "HEAD"],
                          check=True, capture_output=True, text=True).stdout.strip()
    grep = subprocess.run(
        ["git", "-C", args.src, "grep", "-I", "-z", "-n", "-E", GREP_ERE,
         "--"] + pathspec, capture_output=True)
    if grep.returncode not in (0, 1):
        sys.exit(grep.stderr.decode(errors="replace"))

    hits = defaultdict(set)
    for rec in grep.stdout.split(b"\n"):
        if not rec:
            continue
        path, lineno, _ = rec.split(b"\0", 2)
        hits[path.decode(errors="surrogateescape")].add(int(lineno))

    stats = Counter()
    items = []
    for path in sorted(hits):
        try:
            with open(os.path.join(args.src, path), "rb") as f:
                raw = f.read()
        except OSError:
            continue
        text = raw.decode("utf-8", errors="replace")
        lines = text.split("\n")
        lang = lang_of(path, lines[0] if lines else "")
        if lang is None:
            stats["skipped (data/prose file)"] += len(hits[path])
            if misses:
                misses.write("%s: skipped (%d lines)\n" % (path, len(hits[path])))
            continue
        generated = bool(GENERATED_RE.search("\n".join(lines[:15])))
        comments = Comments(text, lang)
        offs = [0]
        for ln in lines:
            offs.append(offs[-1] + len(ln) + 1)

        blocks = {}
        for lineno in sorted(hits[path]):
            idx = lineno - 1
            if idx >= len(lines):
                continue
            line = lines[idx]
            for m in MARKER_RE.finditer(line):
                key = None
                doctext = False
                span = comments.span_at(offs[idx] + m.start()) if comments.spans else None
                if span:
                    s_line = text.count("\n", 0, span[0])
                    if span[2] == "block":
                        e_line = text.count("\n", 0, span[1])
                        key = (s_line, e_line)
                        body = text[span[0]:span[1]].split("\n")
                        trailing = lines[s_line][:span[0] - offs[s_line]].strip() != ""
                    else:
                        col_of = (lambda ln: (ln.find("//") if "//" in ln else
                                              (ln.find("--") if lang == "lua" else -1)))
                        blk = line_comment_block(lines, idx, col_of, lang)
                        if blk:
                            key = (blk[0], blk[1])
                            body = blk[2]
                            trailing = lines[idx][:col_of(lines[idx])].strip() != ""
                elif lang in ("hash", "m4", "semi", "forth", "unknown"):
                    col_of = lambda ln: hash_comment_col(ln, lang if lang != "unknown" else "hash")
                    c = col_of(line)
                    if 0 <= c < m.start():
                        blk = line_comment_block(lines, idx, col_of, lang)
                        if blk:
                            key = (blk[0], blk[1])
                            body = blk[2]
                            trailing = line[:c].strip() != ""
                elif lang == "asm":
                    c = asm_comment_col(line, m.start())
                    if c >= 0:
                        key = (idx, idx)
                        body = [line[c:]]
                        trailing = line[:c].strip() != ""
                elif lang == "roff":
                    c = roff_comment_col(line)
                    if 0 <= c < m.start():
                        col_of = roff_comment_col
                        blk = line_comment_block(lines, idx, col_of, lang)
                        key = (blk[0], blk[1])
                        body = blk[2]
                        trailing = False
                    else:
                        key = (idx, idx)
                        body = [line]
                        trailing = False
                        doctext = True
                if key is None and lang == "c" and line.lstrip().startswith(m.group(1)) \
                        and not line[m.end():].lstrip().startswith("("):
                    # A bare note, usually inside #if 0.
                    key = (idx, idx)
                    body = [line]
                    trailing = False
                if key is None:
                    stats["not in a comment"] += 1
                    if misses:
                        misses.write("%s:%d:%s\n" % (path, lineno, line.strip()))
                    continue
                b = blocks.get(key)
                if b is None:
                    b = blocks[key] = {"markers": [], "marker_lines": [],
                                       "body": body, "trailing": trailing,
                                       "doctext": doctext}
                if m.group(1) not in b["markers"]:
                    b["markers"].append(m.group(1))
                if lineno not in b["marker_lines"]:
                    b["marker_lines"].append(lineno)

        seen = Counter()
        for (s_line, e_line), b in sorted(blocks.items()):
            comment = clean_comment(b["body"])
            norm = normalize(comment)
            seen[norm] += 1
            ident = hashlib.sha1((path + "\0" + norm).encode()).hexdigest()[:12]
            if seen[norm] > 1:
                ident += "-%d" % seen[norm]
            klass = "vendor" if prefixed(path, classes["vendor"]) else "base"
            item = {
                "id": ident,
                "path": path,
                "line": b["marker_lines"][0],
                "start": s_line + 1,
                "end": e_line + 1,
                "marker_lines": sorted(b["marker_lines"]),
                "markers": sorted(set("XXX" if x == "XXXX" else x for x in b["markers"])),
                "lang": lang,
                "area": area_of(path),
                "class": klass,
                "func": enclosing_function(lines, s_line) if lang in ("c", "asm") else "",
                "trailing": b["trailing"],
                "doctext": b["doctext"],
                "generated": generated,
                "comment": comment[:4000],
            }
            items.append(item)
            stats["items"] += 1

    for it in items:
        it["head"] = head
        sys.stdout.write(json.dumps(it, ensure_ascii=False) + "\n")
    for k, v in sorted(stats.items()):
        print("%s: %d" % (k, v), file=sys.stderr)


if __name__ == "__main__":
    main()
